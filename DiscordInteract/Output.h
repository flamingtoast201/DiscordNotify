#include <string>
#include <cpr/cpr.h>
#include <nlohmann/json.hpp>
#include "Defaults.h"
//==============================================================================================
// Forward Declaration
//==============================================================================================
using json = nlohmann::json;
//==============================================================================================
// Declare Class Output Header
//==============================================================================================
class ClassOutput {
public:
    //==========================================================================================
    // Public 
    //==========================================================================================
    // Public Functions
	//------------------------------------------------------------------------------------------
    void send_to_discord(const std::string& title, const std::string& content) {
        cpr::Post(
            cpr::Url{ Defaults::get_discord_webhook() },
            cpr::Header{ {"Content-Type", "application/json"} },
            cpr::Body{ json{
                {"username", "Gemini Build Critic"},
                {"embeds", {{
                    {"title", "⚡ " + title},
                    {"description", content},
                    {"color", 15158332} // High-visibility red/crimson
                }}}
            }.dump() }
        );
    }
	//==========================================================================================
};
